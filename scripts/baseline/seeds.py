"""Write the strata as database seeds (database/seeds/, loaded by `npm run seed`).

Each file is one transaction: delete every non-manual stratum, then upsert
the recomputed ones. The manual workbook is re-read on every build, so this equals
a full replace; the `sources <> 'manual'` rule only protects a manual-only
stratum someone edited in the database by hand.
"""
import json
import os

import pandas as pd

from scripts.scrapers import config

from .coverage import cells
from .schema import ROOM_KEY, WHOLE_UNIT_KEY

PRICE_SEED = os.path.join(config.DATABASE_SEEDS, "001_price_baseline.sql")
ROOM_SEED = os.path.join(config.DATABASE_SEEDS, "003_room_price_baseline.sql")

HEADER = """-- Seed: {what}.
-- Auto-generated by scripts/baseline/build.py from data/processed/baseline_listings.csv
-- (sources: scripts/baseline/sources). Do not hand-edit — re-run the build.
-- Prices in RM/month; medians use price_adjusted (time factor {factor} on {adjusted}).
"""


def _sql(value):
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(round(float(value), 4)) if isinstance(value, float) else str(value)
    if isinstance(value, dict):
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def _vintages(group, registry):
    out = {}
    for name, g in group.groupby("source"):
        dates = g["collected_at"].dropna()
        out[name] = registry[name].vintage or (str(dates.max()) if len(dates) else None)
    return out


def _strata(pooled, key, factor, registry):
    adjusted = {name for name, s in registry.items() if s.time_adjusted}
    stats = {tuple(c[k] for k in key): c for c in cells(pooled, key)}
    rows = []
    for values, g in pooled.groupby(key, dropna=False):
        values = values if isinstance(values, tuple) else (values,)
        values = tuple(int(v) if k == "bedrooms" else v for k, v in zip(key, values))
        c = stats[values]
        row = dict(zip(key, values))
        row.update({
            "median_price": c["median"], "p25_price": c["p25"], "p75_price": c["p75"],
            "sample_size": c["listings"], "building_count": c["buildings"],
            "sources": c["sources"],
            "adjustment_factor": factor if adjusted & set(g["source"]) and factor is not None else None,
            "source_vintages": _vintages(g, registry),
            "status": c["status"],
        })
        if key == ROOM_KEY:
            known = g["private_bathroom"].dropna()
            row["private_bathroom_share"] = (float(known.astype(bool).mean()) if len(known) else None)
        rows.append(row)
    return rows


def _write(path, table, conflict, columns, rows, header):
    values = ",\n".join("  (" + ", ".join(_sql(r[c]) for c in columns) + ")" for r in rows)
    updates = ",\n    ".join(f"{c} = EXCLUDED.{c}" for c in columns if c not in conflict)
    with open(path, "w", encoding="utf-8") as f:
        f.write(header)
        f.write("BEGIN;\n")
        f.write(f"DELETE FROM {table} WHERE sources IS DISTINCT FROM 'manual';\n")
        if rows:
            f.write(f"INSERT INTO {table} ({', '.join(columns)})\nVALUES\n{values}\n")
            f.write(f"ON CONFLICT ({', '.join(conflict)}) DO UPDATE SET\n    {updates},\n"
                    f"    updated_at = now();\n")
        f.write("COMMIT;\n")
    return len(rows)


def write_seeds(pooled, factor, registry):
    """Write both seed files; returns {table: rows written}."""
    adjusted = ", ".join(n for n, s in registry.items() if s.time_adjusted)
    units = pooled[pooled["property_type"] != "room"]
    rooms = pooled[pooled["property_type"] == "room"]

    common = ["median_price", "p25_price", "p75_price", "sample_size", "building_count",
              "sources", "adjustment_factor", "source_vintages", "status"]
    unit_rows = _strata(units, WHOLE_UNIT_KEY, factor, registry)
    for row in unit_rows:
        row["source"] = row["sources"]  # the pre-002 column, kept consistent
    room_rows = _strata(rooms, ROOM_KEY, factor, registry)

    os.makedirs(config.DATABASE_SEEDS, exist_ok=True)
    return {
        "price_baseline": _write(
            PRICE_SEED, "price_baseline", WHOLE_UNIT_KEY, WHOLE_UNIT_KEY + common + ["source"], unit_rows,
            HEADER.format(what="KL/Selangor whole-unit rent baseline", factor=factor, adjusted=adjusted)),
        "room_price_baseline": _write(
            ROOM_SEED, "room_price_baseline", ROOM_KEY, ROOM_KEY + common + ["private_bathroom_share"],
            room_rows, HEADER.format(what="KL/Selangor room-rental baseline", factor=factor, adjusted=adjusted)),
    }
